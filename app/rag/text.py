"""Токенизация для поиска. Лёгкая нормализация русских словоформ усечением: «отпуска», «отпуске», «отпуском» -> «отпус»."""
import re

STOP = set("и в во не что он на я с со как а то все она так его но да ты к у же вы за бы по только ее мне было вот от меня еще нет о из ему теперь когда даже ну вдруг ли если уже или ни быть был него до вас нибудь опять уж вам ведь там потом себя ничего ей может они тут где есть надо ней для мы тебя их чем была сам чтоб без будто чего раз тоже себе под будет ж тогда кто этот того потому этого какой совсем ним здесь этом один почти мой тем чтобы нее сейчас были куда зачем всех никогда можно при наконец два об другой хоть после над больше тот через эти нас про всего них какая много разве три эту моя впрочем хорошо свою этой перед иногда лучше чуть том нельзя такой им более всегда конечно всю между the a an of to is are and or in on for".split())
WORD = re.compile(r"[\w]+", re.UNICODE)
STEM_LEN = 5


def stem(word: str) -> str:
    return word[:STEM_LEN] if len(word) > STEM_LEN else word


def tokens(text: str) -> list[str]:
    return [stem(w) for w in (m.group().lower().replace("ё", "е") for m in WORD.finditer(text)) if w not in STOP and len(w) > 1]
